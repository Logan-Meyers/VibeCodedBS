#!/usr/bin/env python3
"""Generates examples/fib_n.bf: read n, print the nth Fibonacci number.

Brainfuck this size is easy to get wrong by hand, so this script tracks the
pointer and emits the code with comments. Run it from the repo root:

    python3 tools/gen_fib_n.py > examples/fib_n.bf

Big numbers are stored as decimal digits, one digit per 8-cell "group",
least significant digit first. Groups with flag 1 are in use; a group with
flag 0 marks each end, so the number grows as far as the tape allows.
"""

K = 8  # cells per digit group
F, A, B, C, T, W, Z1, Z2 = range(K)  # offsets inside a group
# F flag (1 = digit in use)   A digit of a = fib(i)   B digit of b = fib(i+1)
# C carry in   T sum / scratch   W wrap counter   Z1 Z2 always 0 (scratch)

# Header cells (absolute positions). Group 0 sits right after them and is
# never in use, so walking left over the groups always stops there.
D = [1, 2, 3, 4, 5]  # n as 5 decimal digits, D[0] least significant
GO, CH, NZ, T1, T2, BR, FL = 6, 7, 8, 9, 10, 11, 12
G0 = 16  # group 0 (flag always 0); group 1 starts at G0 + K


class Gen:
    def __init__(self):
        self.lines = []
        self.code = ""
        self.p = 0

    # -- output ----------------------------------------------------------
    def emit(self, s):
        self.code += s

    def line(self, note=""):
        if self.code:
            pad = " " * max(1, 40 - len(self.code)) if note else ""
            self.lines.append(self.code + (pad + "# " + note if note else ""))
        elif note:
            self.lines.append("# " + note)
        self.code = ""

    def comment(self, text=""):
        self.line()
        self.lines.append(("# " + text) if text else "")

    # -- pointer + primitives ---------------------------------------------
    def go(self, c):
        d = c - self.p
        self.emit(">" * d if d > 0 else "<" * -d)
        self.p = c

    def add(self, c, n):
        self.go(c)
        self.emit("+" * n if n > 0 else "-" * -n)

    def clear(self, c):
        self.go(c)
        self.emit("[-]")

    def set(self, c, n):
        self.clear(c)
        self.add(c, n)

    def move(self, src, *dsts):
        """src is added into every dst and left at 0."""
        self.go(src)
        self.emit("[-")
        for d in dsts:
            self.add(d, 1)
        self.go(src)
        self.emit("]")

    def copy(self, src, dst, tmp):
        self.move(src, dst, tmp)
        self.move(tmp, src)

    def loop(self, c, body):
        """while cell c != 0: body (the pointer is back on c each pass)."""
        self.go(c)
        self.emit("[")
        body()
        self.go(c)
        self.emit("]")

    def shift_groups(self, n):
        """Move n groups right (negative: left), keeping the group offset."""
        self.emit((">" if n > 0 else "<") * (abs(n) * K))


def generate():
    g = Gen()
    g.lines += [
        "# fib_n.bf: reads n and prints the nth Fibonacci number, any size",
        "# fib(0) = 0  fib(1) = 1  fib(14) = 377  fib(100) = 354224848179261915075",
        "#",
        "# input: up to 5 digits (n up to 99999) ending in a newline or EOF",
        "# works with plain 8-bit cells: numbers are kept as decimal digits",
        "# the default 30000-cell tape fits answers up to about 3700 digits",
        "# (n up to about 17000); pass --tape for more",
        "#",
        "# GENERATED by tools/gen_fib_n.py; edit that and regenerate",
        "#",
        "# layout: cells 1 to 5 hold n (least significant digit first)",
        f"#         then 8-cell digit groups from cell {G0}: flag a b carry sum w 0 0",
        "#         a and b are fib(i) and fib(i plus 1), least significant group first",
        "",
    ]

    # ---- stage 1: read n --------------------------------------------------
    g.comment("---- stage 1: read n (shift each new digit in at the bottom) ----")
    g.set(GO, 1); g.line("keep reading")

    def read_char():
        g.add(GO, -1); g.line("assume this is the last char")
        g.go(CH); g.emit(","); g.line("next char")

        def not_eof():
            g.add(CH, -10); g.line("newline check")

            def digit():
                g.add(CH, -38); g.line("char to digit value")
                g.clear(D[4])
                for i in (3, 2, 1, 0):
                    g.move(D[i], D[i + 1])
                g.line("shift n up one decimal place")
                g.move(CH, D[0]); g.line("new digit at the bottom")
                g.add(GO, 1); g.line("read another char")

            g.loop(CH, digit)
            g.line()

        g.loop(CH, not_eof)
        g.line()

    g.loop(GO, read_char)
    g.line()

    # ---- start: a = fib(0) = 0, b = fib(1) = 1 in group 1 -----------------
    g.comment("---- a = 0 and b = 1: group 1 in use ----")
    g.add(G0 + K + F, 1)
    g.add(G0 + K + B, 1)
    g.line("group 1: flag = 1  b = 1")

    # ---- stage 2: loop n times -------------------------------------------
    def compute_nz():
        g.clear(NZ)
        for d in D:
            g.copy(d, T1, T2)
            g.loop(T1, lambda: (g.clear(T1), g.set(NZ, 1)))
        g.line("NZ = 1 if n is not 0")

    def decrement_n():
        g.set(BR, 1); g.line("borrow 1")
        for d in D:
            g.move(BR, FL)

            def body(d=d):
                g.add(FL, -1)
                g.add(BR, 1)
                g.copy(d, T1, T2)
                g.add(T2, 1)  # T2 = 1 means "digit was 0"
                g.loop(T1, lambda: (g.clear(T1), g.add(T2, -1), g.add(BR, -1)))
                g.loop(T2, lambda: (g.add(T2, -1), g.add(d, 10)))
                g.add(d, -1)

            g.loop(FL, body)
            g.line(f"digit {d - 1}: 0 becomes 9 and borrows, else just minus 1")

    def step():
        """(a b) = (b a plus b) over all groups; pointer starts and ends on group 0."""
        g.go(G0)
        g.line()
        g.shift_groups(1); g.line("to group 1")
        g.p = 0  # group-relative from here on
        g.emit("[")
        g.line("for each group in use")
        g.move(A, T); g.move(B, A, T); g.move(C, T)
        g.line("sum = a plus b plus carry and a = b")
        g.add(W, 10); g.line("w counts down to the next wrap")

        def count_one():
            g.add(T, -1); g.add(B, 1); g.add(W, -1)
            g.go(W)
            # if w == 0 (non-destructive, uses Z1 Z2): w = 10, b = 0, carry the 1
            g.emit(">+<[>-]>[-")
            g.p = Z1
            g.add(W, 10); g.clear(B); g.add(K + C, 1)
            g.go(Z1)
            g.emit(">]<<")
            g.p = W

        g.loop(T, count_one)
        g.line("b = sum mod 10 and carry into the next group")
        g.clear(W)
        g.go(F)
        g.shift_groups(1)
        g.emit("]")
        g.line("next group")

        g.loop(C, lambda: (g.add(C, -1), g.add(F, 1), g.add(B, 1)))
        g.go(F)
        g.line("carry out of the top: switch on a new group")
        g.shift_groups(-1)
        g.emit("[")
        g.shift_groups(-1)
        g.emit("]")
        g.line("back to group 0")
        g.p = G0  # absolute again

    g.comment("---- stage 2: repeat n times: n minus 1 then (a b) = (b a plus b) ----")
    compute_nz()

    def main_body():
        g.clear(NZ)
        decrement_n()
        step()
        compute_nz()

    g.loop(NZ, main_body)
    g.line()

    # ---- stage 3: print a -------------------------------------------------
    g.comment("BREAKPOINT a = fib(n) is ready; groups from cell 24 hold its digits")
    g.comment("---- stage 3: print a from the top group down, skipping leading zeros ----")
    g.go(G0)
    g.shift_groups(1); g.emit("["); g.shift_groups(1); g.emit("]")
    g.shift_groups(-1)
    g.line("to the top group in use")
    g.p = 0
    g.emit("[")
    g.line("for each group going down")
    # T is the "started printing" flag, handed down from the group above.
    g.copy(A, W, Z1)
    g.loop(W, lambda: (g.clear(W), g.set(T, 1)))
    g.line("started = started or a is not 0")
    g.copy(T, Z1, W)

    def print_digit():
        g.add(Z1, -1)
        g.add(A, 48)
        g.emit(".")

    g.loop(Z1, print_digit)
    g.line("if started: print the digit")
    g.move(T, T - K); g.line("hand started down")
    g.go(F)
    g.shift_groups(-1)
    g.emit("]")
    g.line()
    g.p = G0

    g.set(G0 + W, 1)
    g.loop(G0 + T, lambda: (g.clear(G0 + T), g.add(G0 + W, -1)))
    g.loop(G0 + W, lambda: (g.add(G0 + W, -1), g.add(G0 + Z1, 48), g.emit("."), g.clear(G0 + Z1)))
    g.line("nothing printed: fib(0) is 0")
    g.set(G0 + Z1, 10); g.emit("."); g.line("newline")
    g.line()

    return "\n".join(g.lines) + "\n"


if __name__ == "__main__":
    print(generate(), end="")
